/** `POST /api/sources/resolve` body. */
export const ResolveRequest = z.strictObject({
  url: z.string().trim().min(1).max(2000),
});
export type ResolveRequest = z.infer<typeof ResolveRequest>;

/** `POST /api/sources/resolve` response: what the Add modal's source card shows. */
export const ResolvedSource = z.object({
  /** The source kind for `library`: a YouTube Music link resolves to an artist. */
  kind: SourceKind,
  /** The guessed library: Music for music.youtube.com links, else Video. */
  library: Library,
  /** Channel id (`UC…`) or playlist id. What the source row's `youtubeId` will be. */
  youtubeId: z.string().min(1),
  /** Canonical, id-based URL (`/channel/UC…`, `/playlist?list=…`). */
  url: z.url(),
  name: z.string().min(1),
  avatarUrl: z.url().nullable(),
  /**
   * Total items YouTube reports. Known for playlists; null for channels and artists, whose
   * flat listings carry no total.
   */
  itemCount: z.number().int().nonnegative().nullable(),
  /** From the newest items' dates; null with fewer than two dated items (playlists). */
  uploadsPerWeek: z.number().nonnegative().nullable(),
  /** Publish time of the newest dated item, null when none is dated. */
  latestItemAt: z.iso.datetime().nullable(),
  /** Set when the link was a single video and the source is its channel. */
  resolvedFrom: z.literal('video').nullable(),
  /**
   * The existing source with this YouTube id: the one in the guessed library, else the one in
   * the other library. null when it has not been added.
   */
  alreadyAdded: z.object({ sourceId: z.number().int().positive(), library: Library }).nullable(),
});
export type ResolvedSource = z.infer<typeof ResolvedSource>;

/**
 * Option inputs: every field optional (no defaults) so the API can tell which ones the client
 * set. On create they overlay the defaults (`music.embedCoverArt` from Settings for music), on
 * update the source's current options. Unknown fields are rejected.
 */
export const SourceOptionsInput = z.strictObject({
  embedCoverArt: SourceOptions.shape.embedCoverArt.unwrap().optional(),
  syncOrder: SourceOptions.shape.syncOrder.unwrap().optional(),
});
export type SourceOptionsInput = z.infer<typeof SourceOptionsInput>;

export const SOURCE_NAME_MAX = 200;

/**
 * `POST /api/sources` body. The API resolves `url` again (nothing is cached). `kind` defaults
 * to the resolved kind, mapped to the library: a channel saved to Music becomes an artist and
 * an artist saved to Video a channel. A playlist stays a playlist.
 */
export const CreateSource = z.strictObject({
  url: z.string().trim().min(1).max(2000),
  library: Library,
  kind: SourceKind.optional(),
  /** The rules; the library's default tree from Settings when omitted. */
  matcher: Matcher.optional(),
  options: SourceOptionsInput.optional(),
});
export type CreateSource = z.infer<typeof CreateSource>;

/**
 * `PATCH /api/sources/:id` body. At least one field. `matcher` replaces the rules as a whole
 * (and queues a revalidation); `options` overlay the current options.
 */
export const UpdateSource = z
  .strictObject({
    matcher: Matcher.optional(),
    options: SourceOptionsInput.optional(),
    subscribed: z.boolean().optional(),
    name: z.string().trim().min(1).max(SOURCE_NAME_MAX).optional(),
  })
  .refine((body) => Object.values(body).some((value) => value !== undefined), {
    message: 'Nothing to update',
  });
export type UpdateSource = z.infer<typeof UpdateSource>;

/** `PATCH /api/sources/:id/subscribed` body: the bell. */
export const SetSubscribed = z.strictObject({ subscribed: z.boolean() });
export type SetSubscribed = z.infer<typeof SetSubscribed>;

/** `GET /api/sources` query. Other parameters are ignored. */
export const ListSourcesQuery = z.object({ library: Library.optional() });
export type ListSourcesQuery = z.infer<typeof ListSourcesQuery>;

/** Body of the 409 from `POST /api/sources` when the source already exists in that library. */
export const SourceConflict = z.object({
  statusCode: z.literal(409),
  message: z.string(),
  sourceId: z.number().int().positive(),
});
export type SourceConflict = z.infer<typeof SourceConflict>;

/** `POST /api/sources/:id/rules/preview` body: the rules the Edit modal is about to save. */
export const RulesPreviewRequest = z.strictObject({ matcher: Matcher });
export type RulesPreviewRequest = z.infer<typeof RulesPreviewRequest>;

/**
 * `POST /api/sources/:id/rules/preview` response: the files on disk the candidate rules would
 * remove (`id` is the video or track id), and how many on-disk files they keep.
 */
export const RulesPreview = z.object({
  wouldRemove: z.array(
    z.object({
      id: z.number().int().positive(),
      title: z.string(),
      /** The conditions the item fails (`not older than 90 days`). */
      failing: z.array(z.string()),
    }),
  ),
  wouldKeep: z.number().int().nonnegative(),
});
export type RulesPreview = z.infer<typeof RulesPreview>;
